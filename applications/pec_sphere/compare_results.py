"""
Comparison Utilities for Dielectric Sphere (MoM vs. Mie Theory)

This script is specifically designed to plot and compare the field outputs generated
by the SIE Method of Moments (MoM) solver against the analytical Mie theory results 
generated by `scattnlay` (via `mie_dielectric_sphere_example.py`).

It relies on the local `plot_field.py` utility.

TODO: In the future, we should establish a standardized, application-agnostic format 
for saving and loading electromagnetic field data to avoid maintaining separate plotting scripts.
"""
import matplotlib.pyplot as plt
import os
import pandas as pd
import numpy as np
from plot_field import (
    plot_field_from_csv,
    interpolate_field_on_circle,
    plot_1d_comparison,
    plot_masked_interior_exterior_from_csv,
)

# Change this once to switch between PEC and dielectric application folders.
APP_CASE = "pec_sphere"
DATA_DIRECTORY = f"./applications/{APP_CASE}/data"
PLOTS_DIRECTORY = f"./applications/{APP_CASE}/plots"


def compare_masked_combined_plot(exterior_csv, interior_csv, component, sphere_radius, vmin=None, vmax=None):
    """Generate a stitched 2D plot: interior field inside sphere + exterior field outside sphere."""
    fig, ax = plt.subplots(1, 1, figsize=(9, 7))
    title = f"Masked Combined Field '{component}' (inside: interior, outside: exterior)"
    stitched, _ = plot_masked_interior_exterior_from_csv(
        ax,
        exterior_csv=exterior_csv,
        interior_csv=interior_csv,
        component_to_plot=component,
        sphere_radius=sphere_radius,
        title=title,
        vmin=vmin,
        vmax=vmax,
    )

    if stitched is None:
        print(f"Could not generate masked combined plot for '{component}'.")
        plt.close(fig)
        return

    plt.tight_layout()
    os.makedirs(PLOTS_DIRECTORY, exist_ok=True)
    output_filename = os.path.join(PLOTS_DIRECTORY, f"combined_masked_{component}.png")
    print(f"\nSaving masked combined plot to '{output_filename}'...")
    plt.savefig(output_filename, dpi=150, bbox_inches='tight')
    print("Masked combined plot saved successfully.")
    plt.close(fig)


def compare_masked_combined_vs_mie_2d(
    exterior_csv,
    interior_csv,
    mie_csv,
    component,
    sphere_radius,
    vmin=None,
    vmax=None,
):
    """Compare stitched (inside interior + outside exterior) field against Mie side by side."""
    try:
        df_ext = pd.read_csv(exterior_csv)
        df_int = pd.read_csv(interior_csv)
        df_mie = pd.read_csv(mie_csv)
    except FileNotFoundError as e:
        print(f"Error loading CSV for masked-vs-Mie comparison: {e}")
        return

    try:
        ext_vals = df_ext[component].to_numpy()
        int_vals = df_int[component].to_numpy()
        mie_vals = df_mie[component].to_numpy()
    except KeyError as e:
        print(f"Component not found for masked-vs-Mie comparison: {e}")
        return

    if len(df_ext) != len(df_int):
        print("Interior and exterior CSV sizes do not match; cannot build masked field.")
        return

    x = df_ext["x"].to_numpy()
    z = df_ext["z"].to_numpy()
    inside = (x * x + z * z) <= (sphere_radius * sphere_radius)
    stitched_vals = np.where(inside, int_vals, ext_vals)

    if vmin is None or vmax is None:
        if "magnitude" in component:
            local_vmin = 0.0 if vmin is None else vmin
            local_vmax = max(np.nanpercentile(stitched_vals, 99.5), np.nanpercentile(mie_vals, 99.5))
            local_vmax = 1.2 * local_vmax if vmax is None else vmax
        else:
            absmax = max(np.nanpercentile(np.abs(stitched_vals), 99.5), np.nanpercentile(np.abs(mie_vals), 99.5))
            local_vmin = -absmax if vmin is None else vmin
            local_vmax = absmax if vmax is None else vmax
    else:
        local_vmin, local_vmax = vmin, vmax

    cmap = "viridis" if "magnitude" in component else "RdBu_r"

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(16, 7), sharey=True)

    stitched, _ = plot_masked_interior_exterior_from_csv(
        ax1,
        exterior_csv=exterior_csv,
        interior_csv=interior_csv,
        component_to_plot=component,
        sphere_radius=sphere_radius,
        title="SIE Masked Combined",
        vmin=local_vmin,
        vmax=local_vmax,
    )

    if stitched is None:
        print(f"Could not generate masked combined panel for '{component}'.")
        plt.close(fig)
        return

    plot_field_from_csv(
        ax2,
        mie_csv,
        component,
        "Mie Theory (Analytical) Result",
        vmin=local_vmin,
        vmax=local_vmax,
        cmap=cmap,
    )

    fig.suptitle(f"2D Comparison of '{component}': SIE Masked Combined vs. Mie Theory", fontsize=16)
    plt.tight_layout(rect=[0, 0.03, 1, 0.95])

    os.makedirs(PLOTS_DIRECTORY, exist_ok=True)
    output_filename = os.path.join(PLOTS_DIRECTORY, f"comparison_2d_masked_vs_mie_{component}.png")
    print(f"\nSaving masked-vs-Mie 2D plot to '{output_filename}'...")
    plt.savefig(output_filename, dpi=150, bbox_inches='tight')
    print("Masked-vs-Mie 2D plot saved successfully.")
    plt.close(fig)

def compare_2d_plots(mom_csv, mie_csv, component, vmin, vmax):
    """Generates a side-by-side 2D comparison plot."""
    try:
        df_mom = pd.read_csv(mom_csv)
        df_mie = pd.read_csv(mie_csv)

        # Use manual limits if provided, otherwise calculate them automatically.
        vmin = vmin if vmin is not None else min(df_mom[component].min(), df_mie[component].min())
        vmax = vmax if vmax is not None else max(df_mom[component].max(), df_mie[component].max())

        scale_type = "Manual" if vmin is not None or vmax is not None else "Automatic"
        print(f"Using {scale_type} color scale for '{component}': min={vmin:.4f}, max={vmax:.4f}")

    except (FileNotFoundError, KeyError) as e:
        print(f"Error loading data or finding component for 2D plot: {e}")
        print("Cannot generate 2D comparison plot. Please check file paths and component name.")
        return

    cmap = "viridis" if "magnitude" in component.lower() else "RdBu_r"

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(16, 7), sharey=True)
    plot_field_from_csv(ax1, mom_csv, component, "Method of Moments (MoM) Result", vmin=vmin, vmax=vmax, cmap=cmap)
    plot_field_from_csv(ax2, mie_csv, component, "Mie Theory (Analytical) Result", vmin=vmin, vmax=vmax, cmap=cmap)
    fig.suptitle(f"2D Comparison of '{component}': MoM vs. Mie Theory", fontsize=16)
    plt.tight_layout(rect=[0, 0.03, 1, 0.95])
    
    os.makedirs(PLOTS_DIRECTORY, exist_ok=True)
    source_tag = os.path.splitext(os.path.basename(mom_csv))[0]
    output_filename = os.path.join(PLOTS_DIRECTORY, f"comparison_2d_{component}_{source_tag}.png")
    print(f"\nSaving 2D plot to '{output_filename}'...")
    plt.savefig(output_filename, dpi=150, bbox_inches='tight')
    print("2D plot saved successfully.")
    plt.close(fig) # Close the figure to free memory

def compare_1d_plots(mom_csv, mie_csv, component, radius, num_points, ymin=None, ymax=None):
    """Generates a 1D comparison plot along a circular cut."""
    angles_mom, mom_field = interpolate_field_on_circle(mom_csv, component, radius, num_points)
    angles_mie, mie_field = interpolate_field_on_circle(mie_csv, component, radius, num_points)

    if mom_field is None or mie_field is None:
        print("Could not generate 1D plot due to interpolation errors.")
        return

    data_to_plot = [
        {
            'label': 'MoM',
            'x_data': angles_mom,
            'y_data': mom_field,
            'color': "#ff7f0e",            
            'linestyle': '-',
            'linewidth': 2.2,
            'marker': 'o',
            'markersize': 4,
            'markevery': 12,
            'zorder': 3,
        },
        {
            'label': 'Mie Theory',
            'x_data': angles_mie,
            'y_data': mie_field,
            'color': 'black',
            'linestyle': (0, (3, 3)),
            'linewidth': 3.0,
            'marker': 'o',
            'markersize': 3,
            'markevery': 24,
            'alpha': 0.95,
            'zorder': 4,
        }
    ]
    
    title = f"1D Comparison of '{component}' at Radius {radius}m"
    plot_1d_comparison(data_to_plot, title, 'Angle (radians)', component, ymin=ymin, ymax=ymax)

    os.makedirs(PLOTS_DIRECTORY, exist_ok=True)
    output_filename = os.path.join(PLOTS_DIRECTORY, f"comparison_1d_{component}_r{radius}.png")
    print(f"\nSaving 1D plot to '{output_filename}'...")
    plt.savefig(output_filename, dpi=150, bbox_inches='tight')
    print("1D plot saved successfully.")
    plt.close()


def main():
    """
    Runs 2D and 1D comparisons of MoM and Mie theory results.
    """
    # --- General Configuration ---
    data_directory = DATA_DIRECTORY
    mom_csv_file = os.path.join(data_directory, "fields/total/eh_total_zx_exterior_sie.csv")
    mie_csv_file = os.path.join(data_directory, "eh_total_zx_plane_mie.csv")

    # --- 2D Comparison ---
    component_2d = "Ex_real"
    manual_vmin_2d = -2
    manual_vmax_2d = 2
    compare_2d_plots(mom_csv_file, mie_csv_file, component_2d, manual_vmin_2d, manual_vmax_2d)
    component_2d = "E_magnitude"
    manual_vmin_2d = 0
    manual_vmax_2d = 2
    compare_2d_plots(mom_csv_file, mie_csv_file, component_2d, manual_vmin_2d, manual_vmax_2d)
    
    # --- Physical Parameters (from C++ example) ---
    c0 = 299792458.0
    freq = 1e9  # 1 GHz
    lambda0 = c0 / freq
     # --- 1D Comparison ---
    radius_1d = 3*lambda0  # Radius for the circular cut
    points_1d = 360  # Number of points around the circle
    component_1d = "Ex_real" # Example with manual y-limits
    compare_1d_plots(mom_csv_file, mie_csv_file, component_1d, radius_1d, points_1d)
    component_1d = "Ey_real"
    compare_1d_plots(mom_csv_file, mie_csv_file, component_1d, radius_1d, points_1d, ymin=-1.5, ymax=1.5)
    component_1d = "Ez_real"
    compare_1d_plots(mom_csv_file, mie_csv_file, component_1d, radius_1d, points_1d)
    component_1d = "E_magnitude"
    compare_1d_plots(mom_csv_file, mie_csv_file, component_1d, radius_1d, points_1d)

    component_1d = "Hx_real"
    compare_1d_plots(mom_csv_file, mie_csv_file, component_1d, radius_1d, points_1d, ymin=-1.5, ymax=1.5)
    component_1d = "Hy_real"
    compare_1d_plots(mom_csv_file, mie_csv_file, component_1d, radius_1d, points_1d)
    component_1d = "Hz_real"
    compare_1d_plots(mom_csv_file, mie_csv_file, component_1d, radius_1d, points_1d, ymin=-1.5, ymax=1.5)
    component_1d = "H_magnitude"
    compare_1d_plots(mom_csv_file, mie_csv_file, component_1d, radius_1d, points_1d)

    # Interior and masked comparisons are dielectric-specific. Skip for PEC runs.
    interior_scat_csv = os.path.join(data_directory, "fields/scattered/eh_scat_zx_interior_sie.csv")
    if os.path.exists(interior_scat_csv):
        mom_csv_file = interior_scat_csv
        radius_1d = 1.0*lambda0  # Radius for the circular cut
        component_1d = "E_magnitude"
        compare_1d_plots(mom_csv_file, mie_csv_file, component_1d, radius_1d, points_1d)
        component_2d = "E_magnitude"
        vmin = 0
        vmax = 2
        compare_2d_plots(mom_csv_file, mie_csv_file, component_2d, vmin, vmax)

        component_2d = "Ex_real"
        vmin = -2
        vmax = 2
        compare_2d_plots(mom_csv_file, mie_csv_file, component_2d, vmin, vmax)

        # --- Masked combined dielectric sphere field (inside from interior, outside from exterior) ---
        exterior_total_csv = os.path.join(data_directory, "fields/total/eh_total_zx_exterior_sie.csv")
        sphere_radius = 2.0 * lambda0
        compare_masked_combined_vs_mie_2d(
            exterior_total_csv,
            interior_scat_csv,
            mie_csv_file,
            "E_magnitude",
            sphere_radius,
        )
        compare_masked_combined_vs_mie_2d(
            exterior_total_csv,
            interior_scat_csv,
            mie_csv_file,
            "Ex_real",
            sphere_radius,
        )
    else:
        print("Skipping interior/masked comparisons: interior scattered CSV not found (expected for PEC runs).")



if __name__ == "__main__":
    main()

